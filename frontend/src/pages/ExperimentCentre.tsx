import { api } from '../services/api';
import { useApi } from '../hooks/useApi';
import { EmptyState, ErrorState, Loading, Panel, StatCard, formatNumber } from '../components/primitives';

const REPORTS = ['benchmarks', 'calibration', 'reference', 'training_lightweight', 'training_advanced'];

export default function ExperimentCentre() {
  const experiments = useApi(() => api.experiments(50));
  const benchmarks = useApi(() => api.report('benchmarks'));
  const training = useApi(() => api.report('training_lightweight'));

  const data = benchmarks.data as Record<string, any> | null;
  const trainingData = training.data as Record<string, any> | null;

  return (
    <div className="space-y-6">
      <header>
        <p className="label">07 / Experiment centre</p>
        <h1 className="mt-1 text-2xl font-medium tracking-tight">Reproducibility</h1>
        <p className="mt-1 text-sm text-muted">
          Every number on this page is read from a generated artifact or the experiment registry.
        </p>
      </header>

      <div className="grid gap-3 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard
          label="Lightweight val accuracy"
          value={trainingData ? formatNumber(trainingData.best_val_accuracy, 4) : '—'}
          hint={trainingData ? `epoch ${trainingData.best_epoch} · ${trainingData.wall_clock_seconds}s` : 'training report missing'}
        />
        <StatCard
          label="Test accuracy (light)"
          value={data ? formatNumber(data.lightweight?.clean_test?.accuracy, 4) : '—'}
          hint="frozen test split"
        />
        <StatCard
          label="Test accuracy (advanced)"
          value={data ? formatNumber(data.advanced?.clean_test?.accuracy, 4) : '—'}
          tone="accent"
        />
        <StatCard
          label="Robustness sample"
          value={data?.protocol?.robustness_subsample ?? '—'}
          hint={data ? `${data.protocol.robustness_families.length} families × ${data.protocol.robustness_severities.length} severities` : undefined}
        />
      </div>

      <Panel title="Available reports" subtitle="Generated by the experiment scripts">
        <div className="flex flex-wrap gap-2">
          {REPORTS.map((name) => (
            <a
              key={name}
              href={`/api/v1/reports/${name}`}
              target="_blank"
              rel="noreferrer"
              className="btn text-xs"
            >
              {name}
            </a>
          ))}
        </div>
        <p className="mt-3 text-[11px] leading-relaxed text-muted">
          Reports are served by <code className="font-mono text-accent">/api/v1/reports/{'{name}'}</code> from
          an allow-list. The dashboard shows nothing that was not measured.
        </p>
      </Panel>

      <Panel title="Registry" subtitle="Experiments recorded through the API">
        {experiments.error ? (
          <ErrorState message={experiments.error.message} onRetry={() => void experiments.refresh()} />
        ) : experiments.loading && !experiments.data ? (
          <Loading />
        ) : !experiments.data || experiments.data.items.length === 0 ? (
          <EmptyState message="No experiments registered. POST /api/v1/experiments after a run to record it." />
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full min-w-[720px] text-left">
              <thead>
                <tr className="text-[11px] uppercase tracking-wider text-muted">
                  <th className="pb-2 font-medium">experiment</th>
                  <th className="pb-2 font-medium">status</th>
                  <th className="pb-2 font-medium">seed</th>
                  <th className="pb-2 font-medium">dataset</th>
                  <th className="pb-2 font-medium">metrics</th>
                  <th className="pb-2 font-medium">created</th>
                </tr>
              </thead>
              <tbody>
                {experiments.data.items.map((row) => (
                  <tr key={row.experiment_id} className="table-row">
                    <td className="py-2 font-mono text-xs text-accent">{row.experiment_id}</td>
                    <td className="py-2 text-xs">{row.status}</td>
                    <td className="py-2 font-mono text-xs">{row.seed ?? '—'}</td>
                    <td className="py-2 font-mono text-[11px] text-muted">{row.dataset_id ?? '—'}</td>
                    <td className="py-2 font-mono text-[11px] text-muted">
                      {Object.keys(row.metrics ?? {}).length} keys
                    </td>
                    <td className="py-2 font-mono text-[11px] text-muted">
                      {new Date(row.created_at).toLocaleDateString()}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Panel>

      <Panel title="Environment" subtitle="Hardware and software of the benchmark run">
        {!data?.environment ? (
          <EmptyState message="Benchmark environment unavailable." />
        ) : (
          <dl className="grid gap-2 sm:grid-cols-2 xl:grid-cols-3">
            {Object.entries(data.environment).map(([key, value]) => (
              <div key={key} className="rounded-lg border border-line bg-raised/40 px-3 py-2">
                <dt className="label">{key}</dt>
                <dd className="mt-1 font-mono text-xs text-ink">{String(value)}</dd>
              </div>
            ))}
          </dl>
        )}
      </Panel>
    </div>
  );
}
